"""Full independent MVI-1..8 loaded KL flexoelectric rank qualification.

32 actual nonlinear Green-Lagrange shell cases:
8 fixed ranks x G3D/Gz x STATIC/DYNAMIC (two Newmark steps).

Uses the original independent MVI solver; NEVER calls reference MVI,
strong FDM, energy FDM or mock virtual-work equations.
The common physical case passport is generated by the campaign module.
Projected dynamics are EXPLICITLY opted into and are separately recorded,
not interpreted as full nodal equilibrium. A failed rank is NOT rescued
with another numerical method or changed rank.

This is a research rank-capacity study, not a mesh-convergence or
higher-order free-face physical boundary certificate.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import traceback

import numpy as np

from cylinder_paths import activate
activate()

from independent_mvi import run_coupled_research as mvi
from native_gradient_fdm_mvi_campaign import (
    GRID, NSTEPS, case_id, physical_data, radial_recovery, write_input,
)


def _atomic_json(path,data):
    pending=path.with_name(path.name+".pending")
    try:
        pending.write_text(json.dumps(data,indent=2,allow_nan=False)+"\n",
                           encoding="utf-8")
        pending.replace(path)
    finally:
        pending.unlink(missing_ok=True)


def run(rank,gradient,kind,output):
    if type(rank) is not int or rank not in range(1,9):
        raise ValueError("MVI_RANK_1_TO_8_REQUIRED")
    if gradient not in ("G3D","Gz") or kind not in ("STATIC","DYNAMIC"):
        raise ValueError("MVI_PHYSICAL_CASE_NOT_SUPPORTED")
    item=("KL",gradient,kind,"MVI",rank)
    root=Path(output).resolve()
    root.mkdir(parents=True,exist_ok=False)
    evidence=dict(
        id=case_id(item),method=mvi.METHOD,theory="KL",
        gradient_model=gradient,kind=kind,requested_rank=rank,
        grid=list(GRID),nonzero_curved_outer_face_pressure=True,
        geometry_model="GREEN_LAGRANGE",
        flexoelectric_electrical_modes=2,
        dynamic_projected_opt_in=(kind=="DYNAMIC"),
        full_physical_boundary_certified=False,
        external_accuracy_certified=False,
        mesh_convergence_certified=False,
        status="IN_PROGRESS",git_sha=os.getenv("GITHUB_SHA","UNKNOWN"))
    marker=root/"RANK_EVIDENCE.json"
    _atomic_json(marker,evidence)
    try:
        case_file,forcing,passport=write_input(root/"input",item)
        case=json.loads(case_file.read_text(encoding="utf-8"))
        if case["rank"]!=rank or case["physics"]["theory"]!="KL":
            raise AssertionError("RANK_PASSPORT_INVALID")
        if kind=="DYNAMIC":
            case["solver"]["allow_projected_dynamic"]=True
        else:
            if not case["solver"].get("allow_projected_static"):
                raise AssertionError("RANK_STATIC_PROJECTED_FLAG_MISSING")
        case_file.write_text(json.dumps(case,indent=2)+"\n",
                             encoding="utf-8")
        evidence["physical_passport_sha256"]=passport
        evidence["case_sha256"]=hashlib.sha256(case_file.read_bytes()).hexdigest()
        _atomic_json(marker,evidence)
        preview=mvi.run(case_file,validate_only=True)
        if (not preview.get("validated_only") or
                preview["rank"]!=rank or
                preview["physical_steps_computed"]!=0):
            raise AssertionError("RANK_PREFLIGHT_NOT_VALIDATED")
        prepared=mvi.load_case(case_file)
        print("REAL_MVI_RANK_BEGIN",json.dumps({
            "id":evidence["id"],"git_sha":evidence["git_sha"],
            "fixed_rank":rank,"gradient":gradient,"kind":kind}),flush=True)
        answer=mvi.run(case_file,validate_only=False)
        expected=1 if kind=="STATIC" else NSTEPS
        if answer.get("accepted_steps")!=expected:
            raise AssertionError("RANK_PHYSICAL_STEPS_NOT_ACCEPTED")
        state=root/"input"/"RESULTS"/(
            "STATIC_ACCEPTED.npz" if kind=="STATIC" else f"STEP_{NSTEPS:04d}.npz")
        if not state.is_file():
            raise AssertionError("RANK_ACCEPTED_STATE_NOT_WRITTEN")
        with np.load(state,allow_pickle=False) as fields:
            x=np.asarray(fields["x_profiles"],float)
            y=np.asarray(fields["y_profiles"],float)
            q=np.asarray(fields["mechanical"],float)
            phi=np.asarray(fields["electrical"],float)
            if (x.shape!=(5,rank,GRID[0]) or
                    y.shape!=(5,rank,GRID[1]) or
                    q.shape!=(3,*GRID) or phi.shape!=(2,*GRID)):
                raise AssertionError("RANK_FIELDS_MISMATCH_OR_RANK_REDUCED")
            if not all(np.isfinite(v).all() for v in (x,y,q,phi)):
                raise AssertionError("RANK_NONFINITE_FIELDS")
            if kind=="DYNAMIC":
                for name in ("velocity","acceleration"):
                    if (fields[name].shape!=q.shape or
                            not np.isfinite(fields[name]).all()):
                        raise AssertionError("RANK_INVALID_DYNAMIC_"+name)
        grid=prepared["surface"].grid
        qjets=(q,np.einsum("ij,cjk->cik",grid.dx,q),
               np.einsum("jk,cik->cij",grid.ds,q))
        _,outer,_=radial_recovery(q,"KL",mechanical_jets=qjets)
        max_deflection=float(np.max(np.abs(outer)))
        max_potential=float(np.max(np.abs(phi)))
        if max_deflection<=1.e-14 or max_potential<=1.e-14:
            raise AssertionError("RANK_UNLOADED_OR_UNCOUPLED_RESPONSE")
        quality=answer.get("solution_quality")
        if quality not in ("FULL_NODAL_EQUILIBRIUM","PROJECTED_EQUILIBRIUM",
                           "PROJECTED_WITH_UNREPORTED_STEPS",
                           "UNREPORTED_EQUILIBRIUM"):
            raise AssertionError("RANK_MISSING_EXPLICIT_EQUILIBRIUM_QUALITY")
        if quality=="FULL_NODAL_EQUILIBRIUM" and \
                answer.get("full_nodal_equilibrium_satisfied") is not True:
            raise AssertionError("RANK_FALSE_FULL_NODAL_CERTIFICATE")
        if quality.startswith("PROJECTED") and \
                answer.get("full_nodal_equilibrium_satisfied") is not False:
            raise AssertionError("RANK_FALSE_PROJECTED_CERTIFICATE")
        if answer.get("rank_reduction_performed") is not False:
            raise AssertionError("RANK_REDUCTION_FORBIDDEN")
        np.savez_compressed(root/"PHYSICAL_FIELDS.npz",
            mechanical=q,electrical=phi,outer_radial=outer,
            x_profiles=x,y_profiles=y)
        evidence.update(status="ACCEPTED_RESEARCH_ONLY",
                        accepted_steps=expected,
                        solution_status=answer.get("solution_status"),
                        solution_quality=quality,
                        full_nodal_equilibrium_satisfied=answer.get(
                            "full_nodal_equilibrium_satisfied"),
                        full_nodal_norm=answer.get("full_nodal_norm"),
                        projected_norm_x=answer.get("projected_norm_x"),
                        projected_norm_y=answer.get("projected_norm_y"),
                        dynamic_quality_step_counts=answer.get(
                            "dynamic_quality_step_counts"),
                        radial_at_center_theta0_m=float(outer[GRID[0]//2,0]),
                        radial_max_abs_m=max_deflection,
                        potential_max_abs_v=max_potential)
        _atomic_json(marker,evidence)
        print("REAL_MVI_RANK_ACCEPTED",json.dumps(evidence,allow_nan=False),
              flush=True)
    except BaseException as exc:
        evidence.update(status="FAILED",error_type=type(exc).__name__,
                        error=str(exc))
        _atomic_json(marker,evidence)
        (root/"TRACEBACK.txt").write_text(traceback.format_exc(),encoding="utf-8")
        print("REAL_MVI_RANK_FAILED",evidence["id"],
              type(exc).__name__,str(exc),flush=True)
        raise


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--rank",type=int,required=True)
    parser.add_argument("--gradient",choices=("G3D","Gz"),required=True)
    parser.add_argument("--kind",choices=("STATIC","DYNAMIC"),required=True)
    parser.add_argument("--output",required=True)
    opts=parser.parse_args()
    run(opts.rank,opts.gradient,opts.kind,opts.output)


if __name__=="__main__":
    main()
